// Regenerates collector/lessons.php (lesson + word names for the dashboard) from the app's data files.
// Run after you add lessons:  node collector/make-lessons.mjs
import { UNITS } from '../src/data/curriculum.js';
import { W } from '../src/data/vocab.js';
import { writeFileSync } from 'node:fs';
const q = (s) => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
let L = [];
for (const [ui, u] of UNITS.entries()) for (const [li, l] of u.lessons.entries()) L.push(`  ${q(l.id)} => ${q(`Unit ${ui + 1} · ${u.title.en} · L${li + 1}`)},`);
const Wd = Object.entries(W).map(([k, w]) => `  ${q(k)} => ${q(`${w.en} (${w.fr})`)},`);
writeFileSync(new URL('./lessons.php', import.meta.url), `<?php\n// GENERATED by make-lessons.mjs. Do not edit by hand.\nif (!defined('AFEL')) { http_response_code(403); exit; }\nreturn [\n 'lessons' => [\n${L.join('\n')}\n ],\n 'words' => [\n${Wd.join('\n')}\n ],\n];\n`);
console.log('lessons.php written:', L.length, 'lessons,', Wd.length, 'words');
